D_dev = [0.0] * 426   # PAN/TILT deviation from HOME

G_THRESH = 0.5 * 9.81


def fill_disturbance(ax, t, a, ymin, ymax):
    above = a > G_THRESH
    if not np.any(above):
        return
    in_band, start = False, 0.0
    for i in range(len(above)):
        if above[i] and not in_band:
            start, in_band = t[i], True
        elif not above[i] and in_band:
            ax.axvspan(start, t[i], alpha=0.1, color="red", linewidth=0)
            in_band = False
    if in_band:
        ax.axvspan(start, t[-1], alpha=0.1, color="red", linewidth=0)


def main():
    parser = argparse.ArgumentParser(
        description="Generate paper-quality disturbance rejection figure")
    parser.add_argument("--output-dir", "-o", default=".",
                        help="Output directory (default: current)")
    args = parser.parse_args()
    os.makedirs(args.output_dir, exist_ok=True)

    matplotlib.rcParams.update({
        "font.family": "sans-serif", "font.sans-serif": ["Liberation Sans"],
        "font.size": 10, "axes.labelsize": 11, "legend.fontsize": 9,
        "lines.linewidth": 1.2, "text.usetex": False,
    })

    t = np.array(D_t)
    a = np.array(D_a)

    fig, ax1 = plt.subplots(figsize=(6.5, 3.2))

    ax1.fill_between(t, 0, a, alpha=0.25, color="red", linewidth=0)
    ax1.plot(t, a, "r-", linewidth=0.6, label=r"$|a_{\mathrm{ext}}|$")
    ax1.axhline(G_THRESH, color="red", linestyle=":", linewidth=0.8, alpha=0.5)
    ax1.set_ylabel(r"$|a_{\mathrm{ext}}|$ (m/s$^2$)", color="red")
    ax1.tick_params(axis="y", labelcolor="red")
    ax1.set_ylim(bottom=0)

    ax2 = ax1.twinx()
    ax2.plot(t, D_dev, "b-", linewidth=1.0, label="PAN")
    ax2.plot(t, D_dev, "orange", linewidth=1.0, label="TILT")
    ax2.set_ylabel("Angle Deviation (deg)")
    ax2.set_ylim(-2, 2)

    fill_disturbance(ax2, t, a, -2, 2)
    ax2.set_xlabel("Time (s)")
    ax2.set_xlim(0, t[-1])
    ax2.grid(True, alpha=0.15, linestyle="-", linewidth=0.5)

    lines1, labels1 = ax1.get_legend_handles_labels()
    lines2, labels2 = ax2.get_legend_handles_labels()
    ax2.legend(lines1 + lines2, labels1 + labels2, loc="upper right")

    fig.tight_layout(pad=0.3)
    out_path = os.path.join(args.output_dir, "disturbance_response.pdf")
    fig.savefig(out_path, format="pdf", dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Done: {out_path}")


if __name__ == "__main__":
    main()
