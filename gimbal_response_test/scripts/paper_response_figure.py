# ═══════════════════════════════════════════════════════════════════════════
#  Plot
# ═══════════════════════════════════════════════════════════════════════════

def make_figure(ax_name, t_cmd, v_cmd, t_fb, v_fb, t_min, t_max, out_path):
    """Generate a single paper-quality step response PDF."""
    # Extend command to t_min and t_max for clean staircase
    t_cmd = np.concatenate([[t_min], t_cmd, [t_max]])
    v_cmd = np.concatenate([[v_cmd[0]], v_cmd, [v_cmd[-1]]])

    fig, ax = plt.subplots(figsize=(4.5, 3.2))
    ax.step(t_cmd, v_cmd, "k-", label="Command", linewidth=1.0, where="post")
    ax.plot(t_fb, v_fb, "b-", label="Feedback", linewidth=1.0)
    ax.set_xlabel("Time (s)")
    ax.set_ylabel(f"{ax_name} Angle (deg)")
    ax.set_xlim(t_min, t_max)
    ax.legend(loc="lower right")
    ax.grid(True, alpha=0.15, linestyle="-", linewidth=0.5)
    fig.tight_layout(pad=0.3)
    fig.savefig(out_path, format="pdf", dpi=300, bbox_inches="tight")
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(
        description="Generate paper-quality gimbal step response figures")
    parser.add_argument("--output-dir", "-o", default=".",
                        help="Output directory (default: current)")
    args = parser.parse_args()
    os.makedirs(args.output_dir, exist_ok=True)

    matplotlib.rcParams.update({
        "font.family": "sans-serif", "font.sans-serif": ["Liberation Sans"],
        "font.size": 11, "axes.labelsize": 12, "legend.fontsize": 10,
        "lines.linewidth": 1.2, "text.usetex": False,
    })

    make_figure("PAN",  PAN_t_cmd,  PAN_v_cmd,  PAN_t_fb,  PAN_v_fb,
                PAN_t_min, PAN_t_max,
                os.path.join(args.output_dir, "step_response_pan.pdf"))
    make_figure("TILT", TILT_t_cmd, TILT_v_cmd, TILT_t_fb, TILT_v_fb,
                TILT_t_min, TILT_t_max,
                os.path.join(args.output_dir, "step_response_tilt.pdf"))
    print("Done: step_response_pan.pdf, step_response_tilt.pdf")


if __name__ == "__main__":
    main()
